"""عقرب الرمل (sh:sand_scorpion) v2: تصميم جديد بالكامل بنفس أسماء العظام ومحاورها (فالأنميشن القديم يشتغل بدون تغيير).
القديم: جسم مسطح، ذيل أخضر فاقع ملفوف بأحزمة ما يناسب الجسم البني، وكماشات صغيرة.
الجديد: درع حشرة بلون رمل الصحراء (أحزمة بلمعة وفاصل غامق)، راس بعيون كهرمانية متوهجة (2 كبار + 4 صغار)، 4 حلقات ظهر بحافة غامقة وأشواك،
كماشات كبيرة بيد منتفخة وأصابع غامقة مدببة، 4 أرجل بكل جهة (فخذ يطلع لفوق، ركبة، ساق تنزل، قدم مدببة)، وذيل من 5 عقد يصغر تدريجياً
بحلقات مفاصل غامقة وأشواك ظهر، وينتهي بغدة سم بعروق خضرا متوهجة وإبرة سودة مقوسة بقطرة سم.
التشغيل: python3 tools/gen_scorpion.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_grim_monsters import Rig  # noqa: E402

MATS = {
    "shell": ("chitin", (196, 156, 96), (122, 88, 48)),
    "shell_dk": ("chitin", (132, 94, 54), (72, 50, 28)),
    "belly": ("flat", (222, 198, 146), (222, 198, 146)),
    "joint": ("flat", (66, 46, 28), (66, 46, 28)),
    "claw": ("chitin", (88, 60, 36), (34, 24, 14)),
    "venom": ("glow", (110, 235, 70), (236, 255, 196)),
    "eye": ("glow", (255, 128, 40), (255, 236, 176)),
    "tip": ("obsidian", (30, 24, 20), (96, 74, 52)),
}


def scorpion():
    R = Rig("sh_scorpion", MATS, seed=31)
    R.bone("body", None, (0, 4, 0))
    # ── الراس (prosoma) + عيون + فكوك صغيرة ──
    R.box("body", (-3.0, 3.2, -8.2), (6.0, 2.6, 3.6), "shell", top="shell")
    R.box("body", (-2.6, 5.8, -7.8), (5.2, 0.5, 2.9), "shell_dk")
    for x in (-1.15, 0.35):
        R.box("body", (x, 6.3, -7.3), (0.8, 0.5, 0.8), "eye")                    # عينين كبار فوق الراس
    for sx in (-1, 1):
        for k in range(2):
            R.box("body", (sx * 2.45 - 0.25, 4.9 + k * 0.6, -8.35), (0.5, 0.45, 0.3), "eye")   # عيون صغار بزوايا الراس
        R.box("body", (sx * 1.0 - 0.5, 2.9, -9.1), (1.0, 1.2, 1.0), "joint")      # فكين صغار
    # ── 4 حلقات ظهر (mesosoma) بحافة غامقة وشوكة بالنص ──
    widths = (9.2, 9.8, 9.4, 8.4)
    for k, w in enumerate(widths):
        z0 = -4.6 + k * 2.5
        R.box("body", (-w / 2, 3.0, z0), (w, 3.0, 2.45), "shell")
        R.box("body", (-w / 2 + 0.35, 6.0, z0 + 0.15), (w - 0.7, 0.45, 2.2), "shell_dk")
        R.box("body", (-0.5, 6.45, z0 + 0.7), (1.0, 0.55 + 0.25 * (k % 2), 1.0), "shell")
        for sx in (-1, 1):
            R.box("body", (sx * (w / 2 - 0.9) - 0.35, 6.45, z0 + 0.8), (0.7, 0.4, 0.8), "shell")   # نتوءات جانبية
    R.box("body", (-3.8, 2.6, -4.4), (7.6, 0.4, 9.8), "belly")
    # ── الكماشات: ذراع، مفصل، يد منتفخة، إصبع ثابت (بالعظمة) وإصبع متحرك (fing) ──
    for side, sx in (("l", 1), ("r", -1)):
        cb, fb = f"claw_{side}", f"fing_{side}"
        R.bone(cb, "body", (sx * 4.6, 5, -5))
        R.bone(fb, cb, (sx * 4.1, 4.2, -13.2))
        x = lambda a, w: (a if sx > 0 else -a - w)                                 # مرآة: a = بداية المكعب لجهة اليسار
        R.box(cb, (x(3.7, 1.8), 3.6, -9.0), (1.8, 1.8, 4.2), "shell")
        R.box(cb, (x(3.45, 2.3), 3.35, -9.7), (2.3, 2.3, 0.9), "joint")
        R.box(cb, (x(2.6, 4.0), 2.9, -13.8), (4.0, 3.1, 4.3), "shell", top="shell_dk")
        R.box(cb, (x(2.9, 3.4), 6.0, -13.2), (3.4, 0.4, 3.2), "shell_dk")
        for k in range(3):
            R.box(cb, (x(3.0 + k * 1.1, 0.6), 6.35, -12.6 + k * 0.9), (0.6, 0.7 + (k == 1) * 0.4, 0.6), "claw")   # أشواك فوق اليد
        R.box(cb, (x(2.8, 1.3), 3.1, -16.4), (1.3, 2.1, 2.7), "claw")              # الإصبع الثابت (للداخل)
        R.box(cb, (x(3.0, 0.9), 3.35, -17.3), (0.9, 1.5, 1.0), "claw")
        R.box(cb, (x(3.05, 0.6), 3.55, -17.9), (0.6, 1.0, 0.7), "tip")
        R.box(fb, (x(5.0, 1.3), 3.1, -16.4), (1.3, 2.1, 2.7), "claw")              # الإصبع المتحرك (للخارج)
        R.box(fb, (x(5.2, 0.9), 3.35, -17.3), (0.9, 1.5, 1.0), "claw")
        R.box(fb, (x(5.35, 0.6), 3.55, -17.9), (0.6, 1.0, 0.7), "tip")
        for k in range(2):
            R.box(fb, (x(4.75, 0.3), 3.6, -15.8 + k * 1.0), (0.3, 0.6, 0.5), "belly")   # أسنان داخلية
    # ── الأرجل: 4 بكل جهة (فخذ مايل لفوق 18°، ركبة، ساق، قدم مدببة) ──
    for side, sx in (("l", 1), ("r", -1)):
        lb = f"legs_{side}"
        R.bone(lb, "body", (sx * 3.6, 4, 0))
        # الساق مايلة 22° للخارج حول الركبة (رجل عنكبوتية مفتوحة بدل عمود)، والقدم وين توصل الساق للأرض
        for z in (-4.1, -1.7, 0.7, 3.1):
            if sx > 0:
                R.box(lb, (3.8, 3.4, z), (4.4, 1.1, 1.1), "shell", rot=[0, 0, 18], pivot=[3.8, 4, z + 0.55])
                R.box(lb, (7.45, 4.6, z - 0.1), (1.3, 1.1, 1.3), "joint")
                R.box(lb, (7.65, 0.1, z + 0.08), (0.9, 4.7, 0.95), "shell_dk", rot=[0, 0, 22], pivot=[8.1, 4.8, z + 0.55])
                R.box(lb, (9.45, 0.0, z - 0.3), (0.8, 0.5, 1.6), "claw")
            else:
                R.box(lb, (-8.2, 3.4, z), (4.4, 1.1, 1.1), "shell", rot=[0, 0, -18], pivot=[-3.8, 4, z + 0.55])
                R.box(lb, (-8.75, 4.6, z - 0.1), (1.3, 1.1, 1.3), "joint")
                R.box(lb, (-8.55, 0.1, z + 0.08), (0.9, 4.7, 0.95), "shell_dk", rot=[0, 0, -22], pivot=[-8.1, 4.8, z + 0.55])
                R.box(lb, (-10.25, 0.0, z - 0.3), (0.8, 0.5, 1.6), "claw")
    # ── الذيل: 4 عقد تصغر بحلقة مفصل غامقة وشوكتين على الظهر (الجهة +z)، وغدة السم والإبرة ──
    segs = [("tail1", "body", (0, 5.0, 6.8), [-6, 0, 0], (-2.0, 5.0, 5.0), (4.0, 3.6, 3.8)),
            ("tail2", "tail1", (0, 8.4, 6.9), [14, 0, 0], (-1.8, 8.2, 5.15), (3.6, 3.4, 3.5)),
            ("tail3", "tail2", (0, 11.6, 6.9), [22, 0, 0], (-1.6, 11.4, 5.35), (3.2, 3.2, 3.1)),
            ("tail4", "tail3", (0, 14.6, 6.9), [26, 0, 0], (-1.4, 14.4, 5.55), (2.8, 3.0, 2.7))]
    for name, parent, piv, rot, o, sz in segs:
        R.bone(name, parent, piv, rotation=rot)
        R.box(name, o, sz, "shell")
        R.box(name, (o[0] - 0.22, o[1], o[2] - 0.22), (sz[0] + 0.44, 0.55, sz[2] + 0.44), "joint")
        R.box(name, (-0.3, o[1] + sz[1] * 0.35, o[2] + sz[2]), (0.6, sz[1] * 0.5, 0.5), "shell")              # حافة ظهر وحدة بالنص (مو شوكتين يبينن عيون من ورا)
    R.bone("sting", "tail4", (0, 17.4, 6.9), rotation=[28, 0, 0])
    R.box("sting", (-1.65, 17.2, 5.25), (3.3, 3.2, 3.4), "shell", top="shell_dk")                  # غدة السم
    for sxx in (-1, 1):
        R.box("sting", (sxx * 1.68 - 0.17, 17.7, 5.7), (0.34, 2.0, 0.45), "venom")                 # عروق سم متوهجة على جانبي الغدة
    R.box("sting", (-0.45, 19.0, 8.62), (0.9, 1.4, 0.3), "venom")                                 # عرق خلفي
    R.box("sting", (-0.7, 20.3, 6.0), (1.4, 1.5, 1.4), "tip")                                     # بداية الإبرة
    R.box("sting", (-0.5, 21.5, 6.05), (1.0, 1.5, 1.0), "tip", rot=[-30, 0, 0], pivot=[0, 21.5, 6.55])
    R.box("sting", (-0.35, 22.6, 5.6), (0.7, 1.3, 0.7), "tip", rot=[-58, 0, 0], pivot=[0, 22.6, 5.95])
    R.box("sting", (-0.3, 23.0, 4.55), (0.6, 0.6, 0.6), "venom")                                  # قطرة سم على الرأس
    return R


def main():
    R = scorpion()
    n = R.save(1.6, width=3)
    print("sand scorpion v2 cubes:", n)


if __name__ == "__main__":
    main()
