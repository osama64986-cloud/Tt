"""الخيميائي (sh:alchemist): شيخ بقرية الساكورا يطبخ الجرعات من مواد الوحوش (v1.35).
نفس عظام المدرب ومحاورها (body/head/arm_l/arm_r/leg_l/leg_r) حتى يشتغل بأنميشن المدرب (idle/walk/look).
الشكل: قبعة مخروطية طويلة بحزام بنفسجي وطرف منحني وقنينة معلقة، نظارات نحاس على الجبين، حواجب ولحية طويلة شيبة بحلقة ذهب،
شوارب نازلة، رداء طويل (تركوازي غامق) بحافة ذهبية وياقة، حزام جلد عليه ثلاث قناني (أحمر، أزرق، أخضر) وحقيبة على الورك،
أكمام عريضة بأساور، وجزمة.
التشغيل: python3 tools/gen_alchemist.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_grim_monsters import Rig  # noqa: E402

MATS = {
    "skin": ("flat", (222, 176, 140), (222, 176, 140)),
    "skin_dk": ("flat", (190, 140, 108), (190, 140, 108)),
    "beard": ("fur", (214, 212, 206), (160, 156, 150)),
    "hat": ("cloth", (34, 72, 78), (34, 72, 78)),
    "hat_dk": ("cloth", (22, 46, 52), (22, 46, 52)),
    "band": ("cloth", (110, 60, 170), (110, 60, 170)),
    "robe": ("cloth", (36, 88, 92), (36, 88, 92)),
    "robe_dk": ("cloth", (24, 58, 64), (24, 58, 64)),
    "trim": ("metal", (214, 172, 72), (214, 172, 72)),
    "leather": ("pelt", (106, 70, 42), (138, 96, 58)),
    "leather_dk": ("pelt", (66, 42, 26), (92, 60, 36)),
    "brass": ("metal", (196, 150, 70), (196, 150, 70)),
    "lens": ("glow", (90, 220, 230), (230, 255, 255)),
    "eye": ("flat", (40, 30, 26), (40, 30, 26)),
    "white": ("flat", (240, 240, 236), (240, 240, 236)),
    "vial_r": ("glow", (220, 40, 60), (255, 190, 200)),
    "vial_b": ("glow", (60, 110, 255), (200, 220, 255)),
    "vial_g": ("glow", (80, 220, 110), (210, 255, 220)),
    "pants": ("cloth", (44, 40, 48), (44, 40, 48)),
    "boots": ("pelt", (54, 36, 24), (78, 54, 36)),
}


def mx(o, s):
    return (-(o[0] + s[0]), o[1], o[2])


def alchemist():
    R = Rig("sh_alchemist", MATS, seed=303)
    R.bone("body", None, (0, 12, 0))
    R.bone("head", "body", (0, 24, 0))
    R.bone("arm_l", "body", (5, 22, 0))
    R.bone("arm_r", "body", (-5, 22, 0))
    R.bone("leg_l", "body", (2, 12, 0))
    R.bone("leg_r", "body", (-2, 12, 0))

    def sym(bone, o, s, mat, **kw):
        R.box(bone, o, s, mat, **kw)
        R.box(bone, mx(o, s), s, mat, **kw)

    # ═══ الراس ═══
    R.box("head", (-4, 24, -4), (8, 8, 8), "skin")
    sym("head", (1.1, 27.6, -4.1), (1.7, 1.0, 0.15), "white")                         # بياض العين
    sym("head", (1.15, 27.6, -4.2), (0.75, 1.0, 0.15), "eye")                         # الحدقة (لجهة الأنف)
    sym("head", (0.9, 28.75, -4.25), (2.4, 0.65, 0.35), "beard")                      # حواجب كثيفة شيبة
    R.box("head", (-0.6, 26.3, -4.55), (1.2, 1.7, 0.6), "skin_dk")                    # الخشم
    R.box("head", (-3.0, 25.35, -4.5), (6.0, 1.0, 0.6), "beard")                      # الشوارب
    sym("head", (2.7, 23.9, -4.5), (0.9, 1.7, 0.6), "beard")                          # أطراف الشوارب نازلة
    R.box("head", (-3.2, 20.6, -4.65), (6.4, 3.8, 1.4), "beard")                      # اللحية الطويلة: 3 طبقات تضيق
    R.box("head", (-2.4, 17.8, -4.55), (4.8, 2.9, 1.2), "beard")
    R.box("head", (-1.4, 15.6, -4.45), (2.8, 2.3, 1.0), "beard")
    R.box("head", (-0.95, 14.95, -4.55), (1.9, 0.7, 1.2), "trim")                     # حلقة ذهب باللحية
    R.box("head", (-0.6, 13.7, -4.35), (1.2, 1.3, 0.9), "beard")
    R.box("head", (-4.25, 24.4, 1.6), (8.5, 5.6, 2.6), "beard")                       # شعر شايب من ورا ومن الجوانب
    sym("head", (3.75, 24.6, -2.2), (0.5, 4.6, 3.8), "beard")
    # النظارات على الجبين: حزام وعدستين بإطار نحاس
    R.box("head", (-4.2, 29.7, -4.25), (8.4, 0.8, 0.3), "leather_dk")
    sym("head", (3.95, 29.7, -4.0), (0.3, 0.8, 8.0), "leather_dk")
    sym("head", (0.7, 29.25, -4.65), (2.6, 2.1, 0.5), "brass")
    sym("head", (1.1, 29.6, -4.8), (1.8, 1.4, 0.2), "lens")
    # القبعة المخروطية: حافة، طبقات تضيق، حزام بنفسجي، وطرف منحني لورا
    R.box("head", (-5.6, 32.0, -5.6), (11.2, 0.8, 11.2), "hat_dk")
    R.box("head", (-4.0, 32.8, -4.0), (8.0, 2.6, 8.0), "hat")
    R.box("head", (-4.05, 32.8, -4.05), (8.1, 0.9, 8.1), "band")
    R.box("head", (-3.0, 35.4, -3.0), (6.0, 2.4, 6.0), "hat")
    R.box("head", (-2.0, 37.8, -1.8), (4.0, 2.2, 4.0), "hat", rot=[-10, 0, 0], pivot=[0, 37.8, 0.2])
    R.box("head", (-1.1, 39.6, -0.4), (2.2, 2.0, 2.2), "hat_dk", rot=[-28, 0, 0], pivot=[0, 39.6, 0.7])
    R.box("head", (-0.6, 40.8, 1.4), (1.2, 1.4, 1.2), "hat_dk", rot=[-55, 0, 0], pivot=[0, 40.8, 2.0])
    R.box("head", (4.0, 31.2, -1.0), (0.3, 1.6, 0.3), "trim")                        # خيط القنينة المعلقة
    R.box("head", (3.85, 30.0, -1.15), (0.9, 1.3, 0.9), "vial_b")
    # ═══ الجسم: رداء طويل وياقة وحزام بقناني ═══
    R.box("body", (-4, 12, -2), (8, 12, 4), "robe")
    R.box("body", (-4.4, 2.0, -2.4), (8.8, 10.2, 4.8), "robe", bottom="robe_dk")      # تنورة الرداء (تغطي الرجلين)
    R.box("body", (-4.5, 2.0, -2.5), (9.0, 0.7, 5.0), "trim")                         # حاشية ذهبية
    R.box("body", (-0.45, 2.6, -2.55), (0.9, 21.0, 0.3), "trim")                      # خط ذهبي بنص الرداء
    R.box("body", (-4.6, 21.4, -2.6), (9.2, 2.8, 5.2), "robe_dk", top="robe_dk")      # الياقة
    R.box("body", (-4.65, 21.3, -2.7), (9.3, 0.5, 5.4), "trim")
    R.box("body", (-4.45, 13.2, -2.5), (8.9, 1.2, 5.0), "leather")                    # الحزام
    R.box("body", (-0.8, 13.0, -2.75), (1.6, 1.6, 0.4), "brass")
    for x, m in ((-3.3, "vial_r"), (-2.0, "vial_b"), (1.6, "vial_g")):
        R.box("body", (x, 11.4, -3.0), (1.0, 1.7, 1.0), m)                           # القناني على الحزام
        R.box("body", (x + 0.2, 13.1, -2.9), (0.6, 0.5, 0.6), "leather_dk")           # الفلين
    R.box("body", (-5.5, 8.8, -1.6), (1.4, 3.2, 3.2), "leather", top="leather_dk")   # الحقيبة على الورك
    R.box("body", (-5.6, 11.4, -1.0), (0.4, 2.2, 0.4), "leather_dk")
    # ═══ الذراعين: كم عريض وسوار ذهبي وكف ═══
    for nm, sx in (("arm_l", 1), ("arm_r", -1)):
        def b(o, s, m, **kw):
            R.box(nm, o if sx > 0 else mx(o, s), s, m, **kw)
        b((4.0, 13.0, -2.0), (4.0, 10.0, 4.0), "robe")
        b((3.7, 11.0, -2.35), (4.6, 2.4, 4.7), "robe_dk", bottom="robe_dk")          # كم عريض
        b((3.65, 13.2, -2.4), (4.7, 0.5, 4.8), "trim")
        b((4.3, 9.4, -1.7), (3.4, 1.8, 3.4), "skin")                                  # الكف
    # ═══ الرجلين (تحت الرداء) ═══
    for nm, sx in (("leg_l", 1), ("leg_r", -1)):
        def b(o, s, m, **kw):
            R.box(nm, o if sx > 0 else mx(o, s), s, m, **kw)
        b((0.1, 2.0, -1.9), (3.8, 10.0, 3.8), "pants")
        b((0.0, 0.0, -2.3), (4.0, 2.4, 4.4), "boots", top="boots")
    return R


def main():
    R = alchemist()
    n = R.save(2.6, width=2)
    print("alchemist cubes:", n, "zfixed:", R.zfixed)


if __name__ == "__main__":
    main()
